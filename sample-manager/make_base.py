#!/usr/bin/env python3
"""Generate base_disk.c (the embedded "New Disk" image) for the Orovela
Sample Manager.

Input: a built Orovela OS disk image (e.g. ../DSKA0000_orovela_1.5.hfe, or
the output of ../source/build_unified.py). All 10 slot header sectors are
blanked so New Disk starts empty, then the whole image is emitted as a C array.

Usage: python3 make_base.py <orovela.hfe> [out.c]
Needs mirage_hfe.py on the import path (it lives in ../source; the CMake
build sets this up automatically).
"""
import os, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', 'source'))
from mirage_hfe import MirageHFE

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'DSKA0000_orovela_1.5.hfe')
out = sys.argv[2] if len(sys.argv) > 2 else 'base_disk.c'

fd, tmp = tempfile.mkstemp(suffix='.hfe'); os.close(fd)
try:
    with open(src, 'rb') as f, open(tmp, 'wb') as g:
        g.write(f.read())
    h = MirageHFE(tmp)
    for s in range(10):
        h.write_sector(11 + 6 * s + 4, 5, bytes(512))
    h.save(tmp)

    # sanity: slots empty, OS window untouched
    h2, h0 = MirageHFE(tmp), MirageHFE(src)
    assert all(bytes(h2.read_sector(11 + 6 * s + 4, 5)) == bytes(512) for s in range(10))
    SECMAP = [(1,0),(1,1),(1,2),(1,3),(1,4),(1,5),(2,5),(3,5),(4,5),(5,5),(6,5),(7,5),(8,5),(9,5),(10,5)]
    assert all(bytes(h2.read_sector(t, s)) == bytes(h0.read_sector(t, s)) for t, s in SECMAP)
    assert all(bytes(h2.read_sector(0, s)) == bytes(h0.read_sector(0, s)) for s in range(6))
    d = open(tmp, 'rb').read()
finally:
    os.remove(tmp)

with open(out, 'w') as f:
    f.write('/* generated by make_base.py from %s: slot headers blanked */\n' % os.path.basename(src))
    f.write('const unsigned char BASE_DISK[] = {\n')
    for i in range(0, len(d), 24):
        f.write(','.join(str(b) for b in d[i:i+24]) + ',\n')
    f.write('};\nconst unsigned int BASE_DISK_LEN = %d;\n' % len(d))
print('%s generated from %s (%d bytes)' % (out, src, len(d)))
